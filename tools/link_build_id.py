"""Generate a deterministic multiplayer compatibility ID, without changing mtimes unnecessarily."""
import hashlib
import pathlib
import sys

root = pathlib.Path(__file__).resolve().parents[1]
digest = hashlib.sha256(sys.argv[2].encode())
generated = {
    "include/constants/heal_locations.h", "include/constants/script_commands.h",
    "src/data/map_group_count.h", "src/data/battle_partners.h",
    "src/data/pokemon/teachable_learnsets.h", "src/data/trainers.h",
    "src/data/trainers_frlg.h", "src/data/debug_trainers.h", "src/data/tutor_moves.h",
}
for directory in ("src", "include", "asm", "sound"):
    for source in sorted((root / directory).rglob("*")):
        if (source.is_file() and source.relative_to(root).as_posix() not in generated
                and source.suffix in (".c", ".h", ".inc", ".s", ".party", ".json")):
            digest.update(source.relative_to(root).as_posix().encode())
            digest.update(source.read_bytes().replace(b"\r\n", b"\n"))
token = digest.hexdigest()
content = ('// Generated by tools/link_build_id.py.\n'
           '#define LINK_BUILD_MAGIC_A "' + token[:15] + '"\n'
           '#define LINK_BUILD_MAGIC_B "' + token[15:30] + '"\n'
           '#define LINK_BUILD_ID 0x' + token[:8] + 'u\n')
target = pathlib.Path(sys.argv[1])
target.parent.mkdir(parents=True, exist_ok=True)
if not target.exists() or target.read_text() != content:
    temporary = target.with_suffix(".tmp")
    temporary.write_text(content)
    temporary.replace(target)
